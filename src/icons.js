// An inline 16px Octicon, decorative (the button around it carries the label). `doc` lets the
// caption window create icons in its own document.
export function octicon(name, doc = document) {
  const ns = 'http://www.w3.org/2000/svg';
  const svg = doc.createElementNS(ns, 'svg');
  for (const [k, v] of Object.entries({
    class: 'octicon',
    width: 16,
    height: 16,
    viewBox: '0 0 16 16',
    'aria-hidden': 'true',
    fill: 'currentColor',
  })) {
    svg.setAttribute(k, v);
  }
  for (const d of [PATHS[name]].flat()) {
    const path = doc.createElementNS(ns, 'path');
    path.setAttribute('d', d);
    svg.append(path);
  }
  return svg;
}
